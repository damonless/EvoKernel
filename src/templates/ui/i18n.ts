function serializeDictBlock(dict: UiI18nDict): string {
  const entries = Object.entries(dict).map(
    ([k, v]) => `      ${k}: ${JSON.stringify(v).replace(/</g, '\\u003c').replace(/=/g, '\\u003d')}`
  );
  return `{\n${entries.join(',\n')}\n    }`;
}

export function renderI18nVarJs(): string {
  return `var i18n = {\n    en: ${serializeDictBlock(UI_I18N.en)},\n    zh: ${serializeDictBlock(UI_I18N.zh)}\n  };`;
}
